export function findMatchingFolder(topic = '', category = '') {
  const q = (topic + ' ' + (category || '')).toLowerCase();

  // 1. Exact multi-word matching
  for (const f of LOCAL_AI_FOLDERS) {
    for (const kw of f.keywords) {
      if (kw.includes(' ') && q.includes(kw)) {
        return f;
      }
    }
  }

  // 2. Strict word boundary matching
  for (const f of LOCAL_AI_FOLDERS) {
    for (const kw of f.keywords) {
      const escaped = kw.replace(/[.*+?^$\{\}()|[\]\\]/g, '\\$&');
      const reg = new RegExp('(\\b|^)' + escaped + '(\\b|$)', 'i');
      if (reg.test(q)) {
        return f;
      }
    }
  }

  // 3. Category fallback
  if (category === 'festival') {
    return LOCAL_AI_FOLDERS.find(f => f.id === 'diwali') || LOCAL_AI_FOLDERS[0];
  }
  if (category === 'product') {
    return LOCAL_AI_FOLDERS.find(f => f.id === 'product-launch') || LOCAL_AI_FOLDERS[0];
  }
  if (category === 'hiring') {
    return LOCAL_AI_FOLDERS.find(f => f.id === 'software-dev') || LOCAL_AI_FOLDERS[0];
  }

  return LOCAL_AI_FOLDERS[0];
}

export function getLocalImagesForTopic(topic = '', category = '') {
  const folder = findMatchingFolder(topic, category);
  return {
    folder,
    images: folder?.files || []
  };
}

export function pickImageForTopic(topic = '', category = '', imageIndex = 0) {
  const { folder, images } = getLocalImagesForTopic(topic, category);
  if (!images || images.length === 0) return null;
  const safeIdx = Math.abs(imageIndex) % images.length;
  return {
    folder,
    image: images[safeIdx],
    index: safeIdx,
    total: images.length
  };
}
